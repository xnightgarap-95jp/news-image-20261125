def _unpack(buf):
    n = struct.unpack('>I', buf[:4])[0]
    pos = 4
    out = {}
    for _ in range(n):
        ln = struct.unpack('>I', buf[pos:pos + 4])[0]
        pos += 4
        ch = buf[pos:pos + ln].decode('utf-8')
        pos += ln
        adv, w, h, xoff, yoff, dlen = struct.unpack('>hhhhhI', buf[pos:pos + 14])
        pos += 14
        out[ch] = (adv, w, h, xoff, yoff, buf[pos:pos + dlen])
        pos += dlen
    return out, pos


